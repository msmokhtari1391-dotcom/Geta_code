"""خطاهای مشترک بین مرورگر و خط لوله‌ی ساخت."""


class RateLimitError(RuntimeError):
    """ایجنت به سقف استفاده رسیده است."""


class NeedsLogin(RuntimeError):
    """ایجنت وارد حساب نشده است؛ باید کاربر وارد شود، نه اینکه تلاش مجدد شود."""


class ReadFailed(RuntimeError):
    """ChatGPT/سرویس فقط متن پرامپت را برگردانده؛ پاسخ واقعی خوانده نشده."""


class ConversationFull(RuntimeError):
    """گفتگوی این سرویس به سقف حافظه رسیده؛ باید گفتگوی تازه شروع شود، نه اینکه دوباره در همان گفتگو فرستاده شود."""


class AgentTimeout(TimeoutError):
    """ایجنت بیش از حد مجاز کاری نکرد (شروع نکرد یا پیشرفتی نداشت)؛ باید سراغ ایجنت بعدی رفت."""
